// tools/muse_decode.cpp - strata-muse-decode: Muse Spark Open greedy decoding with the GPU block trunk
// (strata/muse/gpu_trunk.hpp) and the CPU expert lane (strata/muse/expert_lane.hpp), one token per step.
//
//     strata-muse-decode MODEL.gguf [SHARD.gguf...] (--ids 1,2,3 | --dump DIR) [--tokens N] [--threads T] [--graphs]
//                        [--splits N] [--context N] [--worker-root HOST:PORT [--share-b 0.375]]
//
// --worker-root: the two-node expert row split. This process is ucomm rank 0 and bootstraps at HOST:PORT (an address
// of this machine); strata-muse-expert-worker --root HOST:PORT on the other node holds ff rows [cut, ff) of every
// expert and returns their partial outputs each layer (strata/muse/split_lane.hpp), while this node computes [0, cut).
//
// The prompt's tokens run through the same decode step (no batched prefill yet), then N tokens are generated by
// argmax. The generated ids go to stdout; timings to stderr: per generated token the GPU trunk's wall time and the CPU
// lane's. --dump DIR takes the prompt from DIR/tokens.txt (tools/muse_llama_dump.cpp) and, when DIR/result_output.bin
// is there, prints how many prompt positions' argmax agree with llama.cpp. The whole trunk must fit on one GPU: the
// two-layer slice (tools/muse_layer_slice.py) does; the release does not (18.7 GB; the two-card split is not written).
#include "muse_check_common.hpp"
#include "strata/kernels/cpu/native_expert.hpp"
#include "strata/muse/expert_lane.hpp"
#include "strata/muse/gpu_trunk.hpp"
#include "strata/host/muse_names.h"
#include "strata/muse/row_split.hpp"
#include "strata/muse/split_lane.hpp"

#include <chrono>
#include <cstdio>
#include <cstdlib>
#include <sstream>

using namespace muse_check;
namespace cpu = strata::kernels::cpu;

namespace {
strata::muse::HostTensor host(const Model& M, const std::string& name) {
    const strata::TensorInfo& t = M.t(name);
    strata::muse::HostTensor h;
    h.data = M.data(name);
    h.type = (int) t.type;
    h.ne0 = (int64_t) t.shape[0];
    h.ne1 = 1;
    for (size_t k = 1; k < t.shape.size(); ++k) h.ne1 *= (int64_t) t.shape[k];
    h.bytes = (size_t) strata::tensor_payload_bytes(t);
    return h;
}
double now_ms() {
    return std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now().time_since_epoch()).count();
}
}  // namespace

int main(int argc, char** argv) {
    std::vector<std::string> shards;
    std::string ids_arg, dump, worker_root;
    double share_b = 0.375;
    int gen = 16, threads = 15, splits = 1, context = 4096;
    bool graphs = false;
    for (int i = 1; i < argc; ++i) {
        const std::string a = argv[i];
        auto next = [&] { if (i + 1 >= argc) { std::fprintf(stderr, "%s needs a value\n", a.c_str()); std::exit(2); } return std::string(argv[++i]); };
        if (a == "--ids") ids_arg = next();
        else if (a == "--dump") dump = next();
        else if (a == "--tokens") gen = std::stoi(next());
        else if (a == "--threads") threads = std::stoi(next());
        else if (a == "--splits") splits = std::stoi(next());
        else if (a == "--context") context = std::stoi(next());
        else if (a == "--graphs") graphs = true;
        else if (a == "--worker-root") worker_root = next();
        else if (a == "--share-b") share_b = std::stod(next());
        else if (a.rfind("--", 0) == 0) { std::fprintf(stderr, "unknown option %s\n", a.c_str()); return 2; }
        else shards.push_back(a);
    }
    if (shards.empty() || (ids_arg.empty() == dump.empty())) {
        std::fprintf(stderr, "usage: strata-muse-decode MODEL.gguf [SHARD...] (--ids 1,2,3 | --dump DIR) [--tokens N] [--threads T] "
                             "[--graphs] [--splits N] [--context N]\n");
        return 2;
    }
    const strata::GgufModel gm(shards);
    strata::muse::MuseConfig c;
    const std::string err = strata::muse::read_config(gm.meta(), c);
    if (!err.empty()) { std::fprintf(stderr, "%s\n", err.c_str()); return 1; }
    strata::muse::Footprint fp;
    const auto problems = strata::muse::check_tensors(gm, c, fp);
    if (!problems.empty()) { std::fprintf(stderr, "%s\n", problems[0].c_str()); return 1; }
    const Model M{gm};
    std::vector<int> prompt;
    if (!dump.empty()) {
        std::ifstream tf(dump + "/tokens.txt");
        for (int t; tf >> t;) prompt.push_back(t);
    } else {
        std::stringstream ss(ids_arg);
        for (std::string tok; std::getline(ss, tok, ',');) prompt.push_back(std::stoi(tok));
    }
    if (prompt.empty()) { std::fprintf(stderr, "empty prompt\n"); return 1; }
    const int H = (int) c.hidden, L = (int) c.latent, FF = (int) c.expert_ff, P = (int) prompt.size();
    if (P + gen > context) { std::fprintf(stderr, "prompt + tokens exceed --context %d\n", context); return 1; }

    // ---- the GPU trunk (every layer on the current device)
    strata::muse::TrunkConfig tc;
    tc.hidden = H; tc.latent = L; tc.experts = (int) c.experts; tc.top_k = c.top_k; tc.q_heads = (int) c.q_heads;
    tc.kv_heads = (int) c.kv_heads; tc.head_dim = (int) c.head_dim; tc.window = (int) c.window; tc.context = context;
    tc.rms_eps = (float) c.rms_eps; tc.post_eps = (float) c.post_eps; tc.rope_base = (float) c.rope_base_swa;
    tc.expert_weights_scale = (float) c.expert_weights_scale; tc.logit_scale = (float) c.logit_scale;
    tc.softcap = (float) c.softcap; tc.graphs = graphs; tc.attention_splits = splits;
    std::vector<strata::muse::TrunkLayerHost> lh((size_t) c.layers);
    for (int l = 0; l < c.layers; ++l) {
        auto n = [&](const char* s) { return host(M, "blk." + std::to_string(l) + "." + s); };
        auto& x = lh[(size_t) l];
        x.swa = c.swa[(size_t) l] != 0;
        x.attn_norm = n("attn_norm.weight"); x.attn_q = n("attn_q.weight"); x.attn_k = n("attn_k.weight");
        x.attn_v = n("attn_v.weight"); x.attn_gate = n("attn_gate.weight"); x.attn_output = n("attn_output.weight");
        x.attn_q_norm = n("attn_q_norm.weight"); x.attn_k_norm = n("attn_k_norm.weight");
        x.attn_alpha = n("attn_resid_alpha.weight"); x.attn_beta = n("attn_resid_beta.weight");
        x.ffn_norm = n("ffn_norm.weight"); x.post_ffw_norm = n("post_ffw_norm.weight");
        x.ffn_alpha = n("ffn_resid_alpha.weight"); x.ffn_beta = n("ffn_resid_beta.weight");
        x.router = n("ffn_gate_inp.weight"); x.router_bias = n("exp_probs_b.bias");
        x.latent_down = n("ffn_latent_down.weight"); x.latent_up = n("ffn_latent_up.weight");
        x.pre_exp_norm = n("ffn_pre_exp_norm.weight");
    }
    const auto out_norm = host(M, "output_norm.weight"), output = host(M, "output.weight");
    const double t_load = now_ms();
    strata::muse::GpuTrunk gpu(tc, lh, &out_norm, &output);
    std::fprintf(stderr, "muse decode: %d layers, trunk %.2f GB on the GPU (%.1f s), %d CPU expert threads%s%s\n", c.layers,
                 gpu.device_bytes() / 1e9, (now_ms() - t_load) / 1e3, threads, graphs ? ", graphs" : "",
                 splits > 1 ? ", split-K attention" : "");

    // ---- the CPU expert lane over the GGUF's own expert tensors
    cpu::NativeFmt nf;
    std::string ferr;
    if (!cpu::native_fmt((int) M.t("blk.0.ffn_gate_exps.weight").type, (int) M.t("blk.0.ffn_down_exps.weight").type, L, FF, nf, ferr)) {
        std::fprintf(stderr, "%s\n", ferr.c_str());
        return 1;
    }
    // with a worker, this node keeps ff rows [0, cut) of every expert (copied out of the GGUF)
    const int cut = worker_root.empty() ? FF : (int) strata_muse_row_split(FF, 256, share_b);
    if (cut <= 0 || cut > FF) { std::fprintf(stderr, "share %.3f leaves this node no rows\n", share_b); return 1; }
    if (cut < FF && !cpu::native_fmt(nf.gu_type, nf.d_type, L, cut, nf, ferr)) { std::fprintf(stderr, "%s\n", ferr.c_str()); return 1; }
    nf.iq1s_rows = nf.gu_type == GGML_TYPE_IQ1_S;
    strata::muse::ExpertLane lane(nf, L, cut, (float) c.post_eps, threads);
    std::vector<std::vector<float>> post_exp((size_t) c.layers);
    std::vector<strata::muse::LaneLayer> layers((size_t) c.layers);
    std::vector<strata::muse::ExpertShare> share;
    for (int l = 0; l < c.layers; ++l) {
        const std::string p = "blk." + std::to_string(l) + ".";
        post_exp[(size_t) l] = M.all(p + "ffn_post_exp_norm.weight");
        const uint8_t *g = M.data(p + "ffn_gate_exps.weight"), *u = M.data(p + "ffn_up_exps.weight"), *dn = M.data(p + "ffn_down_exps.weight");
        if (cut < FF) {
            share.push_back(strata::muse::slice_experts(g, u, dn, (int) c.experts, L, FF, nf.gu_type, nf.d_type, 0, cut));
            g = share.back().gate.data(); u = share.back().up.data(); dn = share.back().down.data();
        }
        layers[(size_t) l] = {g, u, dn, post_exp[(size_t) l].data()};
    }
    ucomm_t* comm = nullptr;
    std::unique_ptr<strata::muse::SplitLane> split;
    if (cut < FF) {
        ucomm_config cfg;
        ucomm_config_default(&cfg);
        cfg.rank = 0;
        cfg.world = 2;
        cfg.root_addr = worker_root.c_str();
        const ucomm_status us = ucomm_init(&cfg, &comm);
        if (us != UCOMM_OK) { std::fprintf(stderr, "ucomm: %s\n", ucomm_strerror(us)); return 1; }
        split = std::make_unique<strata::muse::SplitLane>(lane, comm, 1, L, (float) c.post_eps);
        std::fprintf(stderr, "muse decode: expert rows [0, %d) here, [%d, %d) on the worker (%s)\n", cut, cut, FF, ucomm_backend_name(comm));
    }

    // ---- prompt, then greedy generation
    const ref::Dims d = dims(c);
    std::vector<float> x, logits, y((size_t) L);
    const Dump llama = dump.empty() ? Dump{} : load_dump(dump + "/result_output.bin");
    const int64_t V = (int64_t) output.ne1;
    int agree = 0, token = prompt[0];
    double gpu_ms = 0, lane_ms = 0, gen_ms = 0;
    std::vector<int> out;
    for (int pos = 0; pos < P + gen - 1; ++pos) {
        token = pos < P ? prompt[(size_t) pos] : token;
        const double t0 = now_ms();
        double lane_step = 0;
        M.rows("token_embd.weight", token, 1, x);
        ref::rms_norm(x.data(), H, d.rms_eps);
        gpu.begin(x.data(), pos);
        for (int l = 0; l < c.layers; ++l) {
            gpu.attention_and_route(l);
            const double l0 = now_ms();
            if (split) split->run(l, layers[(size_t) l], gpu.z().data(), 1, gpu.ids().data(), gpu.weights().data(), c.top_k, y.data());
            else lane.run(layers[(size_t) l], gpu.z().data(), 1, gpu.ids().data(), gpu.weights().data(), c.top_k, y.data());
            lane_step += now_ms() - l0;
            gpu.finish_moe(l, y.data());
        }
        gpu.head(logits);
        const int next = (int) (std::max_element(logits.begin(), logits.end()) - logits.begin());
        const double step = now_ms() - t0;
        if (pos < P && llama.ok() && llama.ne[0] == V)
            agree += next == (int) (std::max_element(llama.f.data() + (size_t) pos * V, llama.f.data() + (size_t) (pos + 1) * V) -
                                    (llama.f.data() + (size_t) pos * V));
        if (pos >= P - 1) {   // the logits of the last prompt token and of every generated token give a new token
            out.push_back(next);
            token = next;
            if (pos >= P) { gen_ms += step; lane_ms += lane_step; gpu_ms += step - lane_step; }
        }
    }
    for (size_t i = 0; i < out.size(); ++i) std::printf("%s%d", i ? " " : "", out[i]);
    std::printf("\n");
    const int timed = (int) out.size() - 1;
    if (timed > 0)
        std::fprintf(stderr, "decode: %d tokens, %.2f tok/s; per token %.1f ms = GPU trunk %.1f + CPU experts %.1f\n", timed,
                     1e3 * timed / gen_ms, gen_ms / timed, gpu_ms / timed, lane_ms / timed);
    if (llama.ok()) std::fprintf(stderr, "prompt argmax agrees with llama.cpp at %d of %d positions\n", agree, P);
    if (split) {
        std::fprintf(stderr, "split: %.2f ms per token waiting for the worker after the local share\n",
                     (int) out.size() + P > 1 ? split->remote_wait_ms() / (P + (int) out.size() - 1) : 0.0);
        split->stop();
        ucomm_finalize(comm);
    }
    return 0;
}
